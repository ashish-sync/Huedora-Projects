import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
if (!source || !fs.existsSync(source)) {
  console.error('Usage: node generate-brand-assets.mjs <source-png>');
  process.exit(1);
}

const publicDir = path.join(__dirname, '../public');
const serverAssets = path.join(__dirname, '../../server/assets');
const logoDataUrlFile = path.join(__dirname, '../src/shared/tyloLogoDataUrl.js');

fs.mkdirSync(publicDir, { recursive: true });
fs.mkdirSync(serverAssets, { recursive: true });
fs.mkdirSync(path.dirname(logoDataUrlFile), { recursive: true });

/** Turn near-black pixels transparent for a clean logo on any background. */
async function removeBlackBackground(inputPath) {
  const { data, info } = await sharp(inputPath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;
  const threshold = 42;

  for (let i = 0; i < data.length; i += channels) {
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    if (r <= threshold && g <= threshold && b <= threshold) {
      data[i + 3] = 0;
    }
  }

  return sharp(data, { raw: { width, height, channels } }).png().trim().toBuffer();
}

const cleaned = await removeBlackBackground(source);

const outputs = [
  { file: path.join(publicDir, 'tylo-one-logo.png'), size: 512 },
  { file: path.join(serverAssets, 'tylo-logo.png'), size: 512 },
  { file: path.join(publicDir, 'favicon-32.png'), size: 32 },
  { file: path.join(publicDir, 'favicon-48.png'), size: 48 },
  { file: path.join(publicDir, 'apple-touch-icon.png'), size: 180 },
];

for (const { file, size } of outputs) {
  await sharp(cleaned)
    .resize(size, size, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toFile(file);
  console.log('Wrote', file);
}

// favicon.ico (32px PNG wrapped as ICO for broad browser support)
const faviconPng = path.join(publicDir, 'favicon.ico.png');
await sharp(cleaned)
  .resize(32, 32, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png()
  .toFile(faviconPng);
await sharp(faviconPng).toFile(path.join(publicDir, 'favicon.ico'));
fs.unlinkSync(faviconPng);
console.log('Wrote', path.join(publicDir, 'favicon.ico'));

const logo512 = await sharp(cleaned)
  .resize(512, 512, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png()
  .toBuffer();
const dataUrl = `data:image/png;base64,${logo512.toString('base64')}`;
fs.writeFileSync(
  logoDataUrlFile,
  `/** Auto-generated by scripts/generate-brand-assets.mjs — do not edit by hand */\nexport const TYLO_LOGO_DATA_URL = ${JSON.stringify(dataUrl)};\n`
);
console.log('Wrote', logoDataUrlFile);
